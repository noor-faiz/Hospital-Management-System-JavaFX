package com.example.finalproject1;

public class PatientData {
    String name1;
    String  pass1;
    String user1;

    public PatientData(String name1, String pass1, String user1) {
        this.name1 = name1;
        this.pass1 = pass1;
        this.user1 = user1;
    }

    public String getName1() {
        return name1;
    }

    public void setName1(String name1) {
        this.name1 = name1;
    }

    public String getPass1() {
        return pass1;
    }

    public void setPass1(String pass1) {
        this.pass1 = pass1;
    }

    public String getUser1() {
        return user1;
    }

    public void setUser1(String user1) {
        this.user1 = user1;
    }
}
